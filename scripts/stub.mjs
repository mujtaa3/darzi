// Generate src/frame-stub.ts from src/frame-stub.js. `npm run build` runs this
// before tsc. The frame has no network, so the stub must reach it as text
// inside the widget document; this script turns the .js file into that text.
import { readFileSync, writeFileSync } from "node:fs";

const source = readFileSync(new URL("../src/frame-stub.js", import.meta.url), "utf8");

// jail.ts puts the stub in a <script> element as it is. The HTML parser would
// end that element at the first "</script", so the stub must never contain one.
if (/<\/script/i.test(source)) {
  throw new Error("src/frame-stub.js must not contain </script");
}

writeFileSync(
  new URL("../src/frame-stub.ts", import.meta.url),
  [
    "// GENERATED by scripts/stub.mjs from src/frame-stub.js. Do not edit this file;",
    "// edit src/frame-stub.js, then run `npm run build`.",
    "",
    "/** The source text of the in-frame helper. jail.ts puts it in each widget document. */",
    `export const FRAME_STUB = ${JSON.stringify(source)};`,
    "",
  ].join("\n"),
);
